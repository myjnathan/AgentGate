// Package distrib implements managed-agent package distribution
// (backlog F20): the platform hosts install packages, employees
// download them, and the hash of a distributed package is registered
// as the reference value for F14 attestation — the "platform
// distributes → platform attests" loop.
//
// The shape follows dsh-ee's offline package import and distribution
// (hikariming/dsh-ee, PR #309 "DSH 分发支持导入内网离线安装包",
// Apache-2.0): an admin uploads or offline-imports an install
// package, the platform hosts it for employees to download, a SHA-256
// checksum is verified and the package is shown as verified or
// unverified, an interrupted import can be resumed, and expired
// packages are cleaned up. dsh-ee's implementation is bound to the
// DSH plugin system, so this package is written for AgentGate's own
// architecture (no code copied); the borrow points are recorded in the
// backlog entry and DEVLOG.
//
// Two package kinds (Nathan 2026-11-22, "dual-package" structure,
// mirroring IP-guard's split):
//
//   - management: the agentgate server for IT — the existing Docker
//     image / offline bundle / systemd shape (see `make bundle`).
//   - user: ag-guard + ag-setup in one installable package for
//     employees, generated by the platform from a policy (gateway
//     URL, data level, desensitization policy, egress allowlist).
//     An employee installs it once; it runs resident, zero-config.
//     Its hash is the F14 attestation baseline.
//
// Files live under the registry root:
//
//	<root>/<package-id>/<filename>   completed package
//	<root>/.uploads/<upload-id>.part in-progress upload
//
// Package metadata is persisted by the store (internal/store); this
// package owns the files and the rules. Upload sessions are likewise
// persisted by the store, so a resume survives a server restart — the
// part file on disk is the authority for how many bytes arrived.
package distrib

import (
	"archive/zip"
	"bytes"
	"crypto/rand"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"
	"sync"
	"time"

	"github.com/myjnathan/agentgate/internal/attest"
)

// MaxPackageSize caps one install package (256 MiB): large enough
// for a Go binary bundle, small enough that a single upload cannot
// fill the data disk by accident.
const MaxPackageSize = 256 << 20

// MaxChunkSize caps one resumable-upload chunk (8 MiB).
const MaxChunkSize = 8 << 20

// Kind is which of the two delivery packages a record is.
type Kind string

const (
	KindManagement Kind = "management" // 管理包: agentgate 服务端, for IT
	KindUser       Kind = "user"       // 用户包: ag-guard + ag-setup, for employees
)

// ParseKind parses "management|user".
func ParseKind(s string) (Kind, bool) {
	switch s {
	case "management":
		return KindManagement, true
	case "user":
		return KindUser, true
	}
	return "", false
}

// Source is how a package reached the platform.
type Source string

const (
	SourceUpload        Source = "upload"         // admin uploaded it online
	SourceOfflineImport Source = "offline-import" // admin imported a file from an offline/air-gapped source
	SourceGenerated     Source = "generated"      // platform generated it (user bundle)
)

// ParseSource parses "upload|offline-import|generated".
func ParseSource(s string) (Source, bool) {
	switch s {
	case "upload":
		return SourceUpload, true
	case "offline-import":
		return SourceOfflineImport, true
	case "generated":
		return SourceGenerated, true
	}
	return "", false
}

// Status is the checksum state of a package. "verified" means the
// stored file's SHA-256 matches the expected checksum the admin (or
// the vendor manifest, for an offline import) supplied; "unverified"
// means no expected checksum was supplied, or it did not match —
// the file is still hosted, but the console says so plainly and the
// package must never be registered as an attestation baseline.
type Status string

const (
	StatusVerified   Status = "verified"
	StatusUnverified Status = "unverified"
	StatusUploading  Status = "uploading"
)

// Package is one hosted install package.
type Package struct {
	ID        string `json:"id"`
	Name      string `json:"name"`
	Kind      Kind   `json:"kind"`
	Version   string `json:"version"`
	Filename  string `json:"filename"`
	SizeBytes int64  `json:"size_bytes"`
	SHA256    string `json:"sha256"`
	// ExpectedSHA256 is the checksum the admin supplied (or the
	// vendor manifest carried); empty when none was supplied.
	ExpectedSHA256 string `json:"expected_sha256,omitempty"`
	Status         Status `json:"status"`
	Source         Source `json:"source"`
	// AgentType names the agent this package installs (dsh,
	// claude-code, ...); it is the key the baseline is registered
	// under in the F14 attestation policy. Empty for a management
	// package, which is not an agent binary.
	AgentType string `json:"agent_type,omitempty"`
	// BaselineRegistered reports whether this package's SHA-256 is
	// currently in the F14 attestation policy's allowed binary
	// hashes for AgentType.
	BaselineRegistered bool       `json:"baseline_registered"`
	ExpiresAt          *time.Time `json:"expires_at,omitempty"`
	CreatedAt          time.Time  `json:"created_at"`
	UploadedBy         string     `json:"uploaded_by,omitempty"`
}

// Upload is one resumable upload session.
type Upload struct {
	ID             string     `json:"id"`
	Name           string     `json:"name"`
	Kind           Kind       `json:"kind"`
	Version        string     `json:"version"`
	Filename       string     `json:"filename"`
	ExpectedSize   int64      `json:"expected_size"`
	ReceivedBytes  int64      `json:"received_bytes"`
	ExpectedSHA256 string     `json:"expected_sha256,omitempty"`
	Source         Source     `json:"source"`
	AgentType      string     `json:"agent_type,omitempty"`
	ExpiresAt      *time.Time `json:"expires_at,omitempty"`
	CreatedAt      time.Time  `json:"created_at"`
	UploadedBy     string     `json:"uploaded_by,omitempty"`
}

// NewID returns a random hex ID with a prefix.
func NewID(prefix string) string {
	var b [8]byte
	_, _ = rand.Read(b[:])
	return prefix + "_" + hex.EncodeToString(b[:])
}

func validName(s string) bool {
	if s == "" || len(s) > 128 {
		return false
	}
	for _, r := range s {
		if r == '/' || r == '\\' || r < 0x20 {
			return false
		}
	}
	return true
}

func validFilename(s string) bool {
	if s == "" || len(s) > 128 || s == "." || s == ".." {
		return false
	}
	for _, r := range s {
		if r == '/' || r == '\\' || r < 0x20 {
			return false
		}
	}
	return true
}

func validSHA256(s string) bool {
	if len(s) != 64 {
		return false
	}
	for _, c := range s {
		if !(c >= '0' && c <= '9' || c >= 'a' && c <= 'f' || c >= 'A' && c <= 'F') {
			return false
		}
	}
	return true
}

// ValidateUpload checks an upload session's metadata before any
// byte is accepted. A generated user bundle never goes through here
// (it is assembled server-side), so "generated" is rejected as a
// source: an upload must be "upload" or "offline-import".
func ValidateUpload(up *Upload) error {
	if up == nil {
		return errors.New("upload is nil")
	}
	if !validName(up.Name) {
		return fmt.Errorf("name must be 1-128 characters without path separators")
	}
	if _, ok := ParseKind(string(up.Kind)); !ok {
		return fmt.Errorf("kind must be management or user")
	}
	if up.Version == "" || !attest.ValidVersion(up.Version) {
		return fmt.Errorf("version must be a dotted numeric version")
	}
	if !validFilename(up.Filename) {
		return fmt.Errorf("filename must be a plain file name (1-128 characters)")
	}
	if up.ExpectedSize <= 0 || up.ExpectedSize > MaxPackageSize {
		return fmt.Errorf("expected_size must be 1-%d bytes", MaxPackageSize)
	}
	if up.ExpectedSHA256 != "" && !validSHA256(up.ExpectedSHA256) {
		return fmt.Errorf("expected_sha256 must be 64 hex characters")
	}
	switch up.Source {
	case SourceUpload, SourceOfflineImport:
	default:
		return fmt.Errorf("source must be upload or offline-import")
	}
	if len(up.AgentType) > 64 {
		return fmt.Errorf("agent_type too long")
	}
	return nil
}

// Registry owns package files under Root.
type Registry struct {
	Root string
	mu   sync.Mutex
}

// NewRegistry returns a registry rooted at dir (created on demand).
func NewRegistry(dir string) *Registry {
	return &Registry{Root: dir}
}

// PathFor returns the on-disk path of a completed package's file.
func (r *Registry) PathFor(pkg *Package) string {
	return filepath.Join(r.Root, pkg.ID, pkg.Filename)
}

// PartPath returns the on-disk path of an upload's partial file.
func (r *Registry) PartPath(up *Upload) string {
	return filepath.Join(r.Root, ".uploads", up.ID+".part")
}

// InitUpload validates the metadata and creates the empty part
// file. It assigns an ID when the upload has none.
func (r *Registry) InitUpload(up *Upload) error {
	if err := ValidateUpload(up); err != nil {
		return err
	}
	if up.ID == "" {
		up.ID = NewID("up")
	}
	if up.CreatedAt.IsZero() {
		up.CreatedAt = time.Now()
	}
	r.mu.Lock()
	defer r.mu.Unlock()
	if err := os.MkdirAll(filepath.Join(r.Root, ".uploads"), 0o700); err != nil {
		return err
	}
	f, err := os.OpenFile(r.PartPath(up), os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0o600)
	if err != nil {
		return fmt.Errorf("create part file: %w", err)
	}
	return f.Close()
}

// ReceivedBytes reports how many bytes of an upload have arrived,
// from the part file on disk — the file is the authority, so a
// resume after a restart or a dropped connection reads the truth.
func (r *Registry) ReceivedBytes(up *Upload) (int64, error) {
	fi, err := os.Stat(r.PartPath(up))
	if err != nil {
		return 0, err
	}
	return fi.Size(), nil
}

// AppendChunk appends data at offset. The offset must equal the
// bytes already received: a chunk that overlaps or skips is rejected
// instead of silently corrupting the file. Chunks larger than
// MaxChunkSize and totals beyond ExpectedSize are rejected.
func (r *Registry) AppendChunk(up *Upload, offset int64, data []byte) (int64, error) {
	if len(data) == 0 {
		return 0, errors.New("empty chunk")
	}
	if len(data) > MaxChunkSize {
		return 0, fmt.Errorf("chunk too large (max %d bytes)", MaxChunkSize)
	}
	if offset < 0 || offset+int64(len(data)) > up.ExpectedSize {
		return 0, fmt.Errorf("chunk exceeds expected size %d", up.ExpectedSize)
	}
	r.mu.Lock()
	defer r.mu.Unlock()
	received, err := r.ReceivedBytes(up)
	if err != nil {
		return 0, fmt.Errorf("upload not found: %w", err)
	}
	if offset != received {
		return 0, fmt.Errorf("offset %d does not match received bytes %d (resume from %d)", offset, received, received)
	}
	f, err := os.OpenFile(r.PartPath(up), os.O_WRONLY|os.O_APPEND, 0o600)
	if err != nil {
		return 0, err
	}
	defer f.Close()
	if _, err := f.Write(data); err != nil {
		return 0, err
	}
	return received + int64(len(data)), nil
}

// CompleteUpload finalizes an upload: the received size must equal
// the expected size, the SHA-256 is computed over the stored file,
// and the status is verified only when an expected checksum was
// supplied and matches. The file is then moved into its package
// directory and the part file disappears.
func (r *Registry) CompleteUpload(up *Upload) (*Package, error) {
	r.mu.Lock()
	defer r.mu.Unlock()
	received, err := r.ReceivedBytes(up)
	if err != nil {
		return nil, fmt.Errorf("upload not found: %w", err)
	}
	if received != up.ExpectedSize {
		return nil, fmt.Errorf("incomplete upload: received %d of %d bytes", received, up.ExpectedSize)
	}
	sum, err := sha256File(r.PartPath(up))
	if err != nil {
		return nil, err
	}
	status := StatusUnverified
	if up.ExpectedSHA256 != "" && strings.EqualFold(sum, up.ExpectedSHA256) {
		status = StatusVerified
	}
	pkg := &Package{
		ID: NewID("pkg"), Name: up.Name, Kind: up.Kind, Version: up.Version,
		Filename: up.Filename, SizeBytes: received, SHA256: sum,
		ExpectedSHA256: up.ExpectedSHA256, Status: status, Source: up.Source,
		AgentType: up.AgentType, ExpiresAt: up.ExpiresAt,
		CreatedAt: time.Now(), UploadedBy: up.UploadedBy,
	}
	dir := filepath.Join(r.Root, pkg.ID)
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return nil, err
	}
	if err := os.Rename(r.PartPath(up), r.PathFor(pkg)); err != nil {
		return nil, err
	}
	return pkg, nil
}

// StoreBytes stores already-assembled bytes (a generated user
// bundle) as a completed package. The caller supplies the package
// record with SHA256/SizeBytes already computed; the hash is
// re-verified here so a caller bug cannot store a mismatched file.
// Status is verified when ExpectedSHA256 is set and matches.
func (r *Registry) StoreBytes(pkg *Package, data []byte) error {
	if pkg == nil || pkg.ID == "" {
		return errors.New("package needs an id")
	}
	if !validFilename(pkg.Filename) {
		return fmt.Errorf("filename must be a plain file name")
	}
	if int64(len(data)) != pkg.SizeBytes {
		return fmt.Errorf("size mismatch: %d bytes for size_bytes %d", len(data), pkg.SizeBytes)
	}
	sum := sha256.Sum256(data)
	if hex.EncodeToString(sum[:]) != pkg.SHA256 {
		return fmt.Errorf("sha256 mismatch for generated package")
	}
	if pkg.ExpectedSHA256 != "" && !strings.EqualFold(pkg.SHA256, pkg.ExpectedSHA256) {
		return fmt.Errorf("expected sha256 does not match generated package")
	}
	r.mu.Lock()
	defer r.mu.Unlock()
	dir := filepath.Join(r.Root, pkg.ID)
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return err
	}
	if err := os.WriteFile(r.PathFor(pkg), data, 0o600); err != nil {
		return err
	}
	if pkg.ExpectedSHA256 != "" {
		pkg.Status = StatusVerified
	} else {
		pkg.Status = StatusUnverified
	}
	return nil
}

// RemoveUpload deletes an in-progress upload's part file.
func (r *Registry) RemoveUpload(up *Upload) error {
	r.mu.Lock()
	defer r.mu.Unlock()
	if err := os.Remove(r.PartPath(up)); err != nil && !os.IsNotExist(err) {
		return err
	}
	return nil
}

// RemovePackage deletes a completed package's files.
func (r *Registry) RemovePackage(pkg *Package) error {
	r.mu.Lock()
	defer r.mu.Unlock()
	if err := os.RemoveAll(filepath.Join(r.Root, pkg.ID)); err != nil {
		return err
	}
	return nil
}

// Expired returns the packages whose expiry has passed.
func Expired(pkgs []*Package, now time.Time) []*Package {
	var out []*Package
	for _, p := range pkgs {
		if p != nil && p.ExpiresAt != nil && now.After(*p.ExpiresAt) {
			out = append(out, p)
		}
	}
	return out
}

// ReadFile returns a completed package's bytes.
func (r *Registry) ReadFile(pkg *Package) ([]byte, error) {
	return os.ReadFile(r.PathFor(pkg))
}

// OpenFile opens a completed package's file for streaming.
func (r *Registry) OpenFile(pkg *Package) (*os.File, error) {
	return os.Open(r.PathFor(pkg))
}

func sha256File(path string) (string, error) {
	f, err := os.Open(path)
	if err != nil {
		return "", err
	}
	defer f.Close()
	h := sha256.New()
	if _, err := io.Copy(h, f); err != nil {
		return "", err
	}
	return hex.EncodeToString(h.Sum(nil)), nil
}

// ---- user bundle generation ----

// validDataLevel reports whether s is a data level name. It mirrors
// store.ParseDataLevel without importing the store package (the store
// holds distrib records, so distrib cannot import it back).
func validDataLevel(s string) bool {
	switch s {
	case "public", "internal", "confidential", "secret":
		return true
	}
	return false
}

// BundleComponent is one binary inside a generated user bundle.
type BundleComponent struct {
	Role     string // "ag-guard" | "ag-setup"
	Filename string
	Data     []byte
	SHA256   string
}

// UserBundleConfig is the policy baked into a generated user
// package: the gateway the sidecar talks to, the highest data level
// the install may carry, and the egress allowlist. It is written
// into guard.json inside the zip, so the employee installs once and
// runs zero-config.
type UserBundleConfig struct {
	Name            string
	Version         string
	AgentType       string
	GatewayURL      string
	MaxDataLevel    string // public|internal|confidential|secret
	EgressAllowlist []string
	GeneratedAt     time.Time
}

// BundleManifest is MANIFEST.json inside a generated user bundle.
type BundleManifest struct {
	Name        string `json:"name"`
	Version     string `json:"version"`
	AgentType   string `json:"agent_type"`
	GeneratedAt string `json:"generated_at"`
	GatewayURL  string `json:"gateway_url"`
	Components  []struct {
		Role     string `json:"role"`
		Filename string `json:"filename"`
		SHA256   string `json:"sha256"`
		Size     int64  `json:"size_bytes"`
	} `json:"components"`
	GuardConfigSHA256 string `json:"guard_config_sha256"`
}

// GenerateUserBundle assembles a user package zip from exactly two
// components (ag-guard + ag-setup) plus the generated guard.json
// policy file and a MANIFEST.json. The zip is deterministic in entry
// order; the returned hex string is the SHA-256 of the zip itself.
func GenerateUserBundle(cfg UserBundleConfig, components []BundleComponent) ([]byte, string, error) {
	if !validName(cfg.Name) {
		return nil, "", fmt.Errorf("name must be 1-128 characters without path separators")
	}
	if cfg.Version == "" || !attest.ValidVersion(cfg.Version) {
		return nil, "", fmt.Errorf("version must be a dotted numeric version")
	}
	if len(cfg.AgentType) == 0 || len(cfg.AgentType) > 64 {
		return nil, "", fmt.Errorf("agent_type must be 1-64 characters")
	}
	if !strings.HasPrefix(cfg.GatewayURL, "https://") && !strings.HasPrefix(cfg.GatewayURL, "http://127.0.0.1") && !strings.HasPrefix(cfg.GatewayURL, "http://localhost") {
		return nil, "", fmt.Errorf("gateway_url must be https (or loopback http for testing)")
	}
	if !validDataLevel(cfg.MaxDataLevel) {
		return nil, "", fmt.Errorf("max_data_level must be public|internal|confidential|secret")
	}
	for _, e := range cfg.EgressAllowlist {
		if e == "" || len(e) > 253 || strings.ContainsAny(e, " \t/") {
			return nil, "", fmt.Errorf("egress allowlist entries must be host names")
		}
	}
	if len(components) != 2 {
		return nil, "", fmt.Errorf("a user bundle needs exactly two components (ag-guard + ag-setup)")
	}
	seen := map[string]bool{}
	for i := range components {
		c := &components[i]
		if c.Role != "ag-guard" && c.Role != "ag-setup" {
			return nil, "", fmt.Errorf("component role must be ag-guard or ag-setup")
		}
		if seen[c.Role] {
			return nil, "", fmt.Errorf("duplicate component role %q", c.Role)
		}
		seen[c.Role] = true
		if !validFilename(c.Filename) {
			return nil, "", fmt.Errorf("component filename must be a plain file name")
		}
		if len(c.Data) == 0 || int64(len(c.Data)) > MaxPackageSize {
			return nil, "", fmt.Errorf("component %q must be 1-%d bytes", c.Role, MaxPackageSize)
		}
		sum := sha256.Sum256(c.Data)
		c.SHA256 = hex.EncodeToString(sum[:])
	}
	if !seen["ag-guard"] || !seen["ag-setup"] {
		return nil, "", fmt.Errorf("a user bundle needs both ag-guard and ag-setup")
	}
	if cfg.GeneratedAt.IsZero() {
		cfg.GeneratedAt = time.Now()
	}
	guardCfg, err := json.MarshalIndent(map[string]any{
		"gateway_url":      cfg.GatewayURL,
		"max_data_level":   cfg.MaxDataLevel,
		"egress_allowlist": cfg.EgressAllowlist,
		"agent_type":       cfg.AgentType,
		"package":          cfg.Name,
		"version":          cfg.Version,
	}, "", "  ")
	if err != nil {
		return nil, "", err
	}
	guardSum := sha256.Sum256(guardCfg)
	manifest := BundleManifest{
		Name: cfg.Name, Version: cfg.Version, AgentType: cfg.AgentType,
		GeneratedAt:       cfg.GeneratedAt.UTC().Format(time.RFC3339),
		GatewayURL:        cfg.GatewayURL,
		GuardConfigSHA256: hex.EncodeToString(guardSum[:]),
	}
	for _, c := range components {
		manifest.Components = append(manifest.Components, struct {
			Role     string `json:"role"`
			Filename string `json:"filename"`
			SHA256   string `json:"sha256"`
			Size     int64  `json:"size_bytes"`
		}{Role: c.Role, Filename: c.Filename, SHA256: c.SHA256, Size: int64(len(c.Data))})
	}
	manifestBytes, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		return nil, "", err
	}
	var buf bytes.Buffer
	zw := zip.NewWriter(&buf)
	writeEntry := func(name string, data []byte) error {
		hdr := &zip.FileHeader{Name: name, Method: zip.Deflate}
		hdr.SetModTime(cfg.GeneratedAt)
		w, err := zw.CreateHeader(hdr)
		if err != nil {
			return err
		}
		_, err = w.Write(data)
		return err
	}
	for _, c := range components {
		if err := writeEntry(c.Role, c.Data); err != nil {
			return nil, "", err
		}
	}
	if err := writeEntry("guard.json", guardCfg); err != nil {
		return nil, "", err
	}
	if err := writeEntry("MANIFEST.json", manifestBytes); err != nil {
		return nil, "", err
	}
	if err := zw.Close(); err != nil {
		return nil, "", err
	}
	sum := sha256.Sum256(buf.Bytes())
	return buf.Bytes(), hex.EncodeToString(sum[:]), nil
}
